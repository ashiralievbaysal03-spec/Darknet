# ЗАДАЧА 12. Среднее без чётных
# ----------------------------------------
#
# Условие:
#   Найти среднее арифметическое элементов списка,
#   ИСКЛЮЧАЯ чётные числа. Если чётных нет - вернуть обычное среднее.
#
# Данные:
#   Ввод: [10, 3, 20, 7] -> Вывод: 5.0     ((3+7)/2)
#   Ввод: [2, 4, 6]      -> Вывод: 4.0     (обычное среднее)
#   Ввод: [1, 2, 3]      -> Вывод: 2.0     ((1+3)/2)
#

numbers = [10, 3, 20, 7]

odd_numbers = []

for n in numbers:
    if n % 2 != 0:
        odd_numbers.append(n)

if len(odd_numbers) > 0:
    result = sum(odd_numbers) / len(odd_numbers)
else:
    result = sum(numbers) / len(numbers)

print(result)
