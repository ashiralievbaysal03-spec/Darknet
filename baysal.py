# ЗАДАЧА 20. Частотный анализ слов
# ----------------------------------------------------------------
# Условие:
#     Запросить строку. Разбить на слова, привести к нижнему регистру,
#     удалить знаки препинания (.,!?;:).
#     Вывести словарь «слово → сколько раз встречается»,
#     отсортированный по убыванию частоты.
#
# Данные:
#     Ввод:  "Я люблю Python. Python — это круто!"
#     Вывод: python: 2, я: 1, люблю: 1, это: 1, круто: 1
#
#     Ввод:  "Привет, привет, ПРИВЕТ!"
#     Вывод: привет: 3
text = input("Введите строку: ")

text = text.lower()

symbols = ".,!?;:"

for char in symbols:
    text = text.replace(char, "")

words = text.split()

counts = {}

for word in words:
    if word in counts:
        counts[word] += 1
    else:
        counts[word] = 1

sorted_words = sorted(
    counts.items(),
    key=lambda x: x[1],
    reverse=True
)

for word, count in sorted_words:
    print(word + ":", count)
