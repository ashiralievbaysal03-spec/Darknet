# ----------------------------------------------------------------
# Условие:
#     Пользователь вводит выражения вида "10 + 5", "7 * 3", пока не
#     введёт "exit". Вывести результат каждого выражения.
#     Обработать деление на ноль и неизвестную операцию.
#
# Данные:
#     Ввод:  10 + 5    -> Вывод: 15
#     Ввод:  20 / 4    -> Вывод: 5.0
#     Ввод:  7 / 0     -> Вывод: деление на ноль
#     Ввод:  7 # 6     -> Вывод: неизвестная операция
#     Ввод:  exit      -> Вывод: (выход)
#
while True:
    text = input("Введите выражение: ")

    if text == "exit":
        print("Выход")
        break

    parts = text.split()

    a = float(parts[0])
    operation = parts[1]
    b = float(parts[2])

    if operation == "+":
        print(a + b)

    elif operation == "-":
        print(a - b)

    elif operation == "*":
        print(a * b)

    elif operation == "/":
        if b == 0:
            print("деление на ноль")
        else:
            print(a / b)

    else:
        print("неизвестная операция")


